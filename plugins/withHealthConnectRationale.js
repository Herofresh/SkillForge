/**
 * Config plugin (PLAN 7.10, ADR-072): Health Connect's "privacy policy" link opens SkillForge's
 * privacy policy instead of the app's home screen.
 *
 * Health Connect requires every app with health permissions to show its privacy policy when the
 * user taps that link: through Android 13 it starts the activity that handles
 * `androidx.health.ACTION_SHOW_PERMISSIONS_RATIONALE`, from Android 14 the activity alias
 * `ViewPermissionUsageActivity` (`VIEW_PERMISSION_USAGE` + `HEALTH_PERMISSIONS`). The
 * `react-native-health-connect` plugin points both at the main activity, which would only open the
 * app. This plugin adds a tiny `HealthPermissionsRationaleActivity` that opens the privacy policy
 * page in the browser and closes, and points both entries at it.
 *
 * The manifest transform is a pure function (tested in withHealthConnectRationale.test.ts). It
 * works whether or not the library's plugin already ran, so plugin order doesn't matter.
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const PRIVACY_POLICY_URL = 'https://herofresh.github.io/SkillForge/privacy/#health-connect';
const RATIONALE_ACTION = 'androidx.health.ACTION_SHOW_PERMISSIONS_RATIONALE';
const ALIAS_NAME = 'ViewPermissionUsageActivity';
const ACTIVITY_NAME = '.HealthPermissionsRationaleActivity';
const ACTIVITY_CLASS = 'HealthPermissionsRationaleActivity';

const hasAction = (intentFilter, action) =>
  (intentFilter.action || []).some((entry) => entry.$['android:name'] === action);

/** The alias Android 14+ starts from the Health Connect permission screen. */
function rationaleAlias() {
  return {
    $: {
      'android:name': ALIAS_NAME,
      'android:exported': 'true',
      'android:targetActivity': ACTIVITY_NAME,
      'android:permission': 'android.permission.START_VIEW_PERMISSION_USAGE',
    },
    'intent-filter': [
      {
        action: [{ $: { 'android:name': 'android.intent.action.VIEW_PERMISSION_USAGE' } }],
        category: [{ $: { 'android:name': 'android.intent.category.HEALTH_PERMISSIONS' } }],
      },
    ],
  };
}

/**
 * The manifest with the rationale activity (handling the Android 13 action), the alias pointing at
 * it, and the action removed from every other activity. Mutates and returns `manifest`.
 */
function applyHealthConnectRationale(manifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  application.activity = application.activity || [];
  for (const activity of application.activity) {
    if (activity.$['android:name'] === ACTIVITY_NAME) continue;
    if (activity['intent-filter']) {
      activity['intent-filter'] = activity['intent-filter'].filter(
        (intentFilter) => !hasAction(intentFilter, RATIONALE_ACTION),
      );
    }
  }
  if (!application.activity.some((activity) => activity.$['android:name'] === ACTIVITY_NAME)) {
    application.activity.push({
      $: {
        'android:name': ACTIVITY_NAME,
        'android:exported': 'true',
        'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
      },
      'intent-filter': [{ action: [{ $: { 'android:name': RATIONALE_ACTION } }] }],
    });
  }
  application['activity-alias'] = [
    ...(application['activity-alias'] || []).filter(
      (alias) => alias.$['android:name'] !== ALIAS_NAME,
    ),
    rationaleAlias(),
  ];
  return manifest;
}

/** The Kotlin source of the activity: open the policy, then close. */
function rationaleActivitySource(packageName) {
  return `package ${packageName}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

/** Generated by plugins/withHealthConnectRationale.js (PLAN 7.10): Health Connect's privacy policy link. */
class ${ACTIVITY_CLASS} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    startActivity(Intent(Intent.ACTION_VIEW, Uri.parse("${PRIVACY_POLICY_URL}")))
    finish()
  }
}
`;
}

const withHealthConnectRationale = (config) => {
  config = withAndroidManifest(config, (mod) => {
    applyHealthConnectRationale(mod.modResults);
    return mod;
  });
  return withDangerousMod(config, [
    'android',
    (mod) => {
      const packageName = mod.android && mod.android.package;
      if (!packageName) throw new Error('withHealthConnectRationale needs android.package');
      const dir = path.join(
        mod.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...packageName.split('.'),
      );
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(
        path.join(dir, `${ACTIVITY_CLASS}.kt`),
        rationaleActivitySource(packageName),
      );
      return mod;
    },
  ]);
};

module.exports = withHealthConnectRationale;
module.exports.applyHealthConnectRationale = applyHealthConnectRationale;
module.exports.rationaleActivitySource = rationaleActivitySource;
module.exports.PRIVACY_POLICY_URL = PRIVACY_POLICY_URL;
module.exports.RATIONALE_ACTION = RATIONALE_ACTION;

/**
 * Turns the YAML sources in `content/progressions/` into the checked dataset and its two generated
 * outputs: the typed module the app imports and the coach review sheet (ADR-016).
 *
 * Pure: it takes file contents and returns strings. File I/O lives in `scripts/progressions.ts`.
 */
import { nodeAttributes } from '@/domain/character';
import { BRANCHES } from '@/domain/types';
import type { Branch, ExerciseNode, Metric, Trial, ValidationIssue } from '@/domain/types';

import { parseBranchFile } from './progressionFormat';
import { BRANCH_NAMES } from './skills/branches';
import { validateNodes } from './validate';

/** Repo-relative, POSIX-style paths. */
export const PROGRESSIONS_DIR = 'content/progressions';
export const GENERATED_MODULE_PATH = 'src/data/skills/progressions.generated.ts';
export const REVIEW_SHEET_PATH = 'docs/review/progression-matrix.md';

export function branchFilePath(branch: Branch): string {
  return `${PROGRESSIONS_DIR}/${branch}.yaml`;
}

export interface SourceFile {
  /** Repo-relative POSIX path, e.g. `content/progressions/v_pull.yaml`. */
  path: string;
  text: string;
}

export interface BuildResult {
  /** Sorted by branch (in `BRANCHES` order), then chainOrder. */
  nodes: ExerciseNode[];
  issues: ValidationIssue[];
}

/** Parses every branch file, checks each against its file name, then validates the whole set. */
export function buildMatrix(files: readonly SourceFile[]): BuildResult {
  const issues: ValidationIssue[] = [];
  const nodes: ExerciseNode[] = [];
  const expected = new Set<string>(BRANCHES.map(branchFilePath));

  for (const file of files) {
    if (!expected.has(file.path)) {
      issues.push({
        file: file.path,
        message: `unexpected file; branch files are named after a branch (${BRANCHES.join(', ')})`,
      });
      continue;
    }
    const parsed = parseBranchFile(file.text, file.path);
    issues.push(...parsed.issues);
    if (parsed.branch !== undefined && branchFilePath(parsed.branch) !== file.path) {
      issues.push({
        file: file.path,
        message: `says 'branch: ${parsed.branch}' but the file name differs`,
      });
      continue;
    }
    nodes.push(...parsed.nodes);
  }
  for (const branch of BRANCHES) {
    if (!files.some((file) => file.path === branchFilePath(branch))) {
      issues.push({ file: branchFilePath(branch), message: 'file is missing' });
    }
  }

  const fileOf = (nodeId: string | undefined) => {
    const node = nodes.find((n) => n.id === nodeId);
    return node ? branchFilePath(node.branch) : undefined;
  };
  for (const issue of validateNodes(nodes)) issues.push({ ...issue, file: fileOf(issue.nodeId) });

  return { nodes: sortNodes(nodes), issues };
}

export function sortNodes(nodes: readonly ExerciseNode[]): ExerciseNode[] {
  const branchIndex = (branch: Branch) => BRANCHES.indexOf(branch);
  return [...nodes].sort(
    (a, b) => branchIndex(a.branch) - branchIndex(b.branch) || a.chainOrder - b.chainOrder,
  );
}

const GENERATED_HEADER = [
  '// GENERATED FILE - DO NOT EDIT.',
  '// Source: content/progressions/*.yaml. Rebuild with `npm run progressions:build`.',
].join('\n');

/** The typed module the app imports. The YAML is never parsed on the phone. */
export function renderGeneratedModule(nodes: readonly ExerciseNode[]): string {
  return [
    GENERATED_HEADER,
    "import type { ExerciseNode } from '@/domain/types';",
    '',
    `export const GENERATED_NODES: readonly ExerciseNode[] = ${JSON.stringify(nodes, null, 2)};`,
    '',
  ].join('\n');
}

